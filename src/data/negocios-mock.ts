function horarios(
  abre = "09:00",
  fecha = "18:00",
  domingo?: { abre: string; fecha: string } | "fechado",
): HorarioFuncionamento[] {
  return ([0, 1, 2, 3, 4, 5, 6] as const).map((dia) => {
    if (dia === 0) {
      if (domingo === "fechado") {
        return { dia, abre: null, fecha: null, fechado: true };
      }
      return {
        dia,
        abre: domingo?.abre ?? "09:00",
        fecha: domingo?.fecha ?? "13:00",
        fechado: false,
      };
    }
    return { dia, abre, fecha, fechado: false };
  });
}

